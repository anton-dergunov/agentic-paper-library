#!/usr/bin/env python3
"""The engine's conversion tickets, with how many papers of the library each one touches.

    paperlib tickets            # print the summary
    paperlib tickets --write    # also regenerate tickets/README.md from it

A ticket is one cause of conversion problems: tickets/<id>.md, its frontmatter giving
`id`, `title`, `converter` (pdf, html, web or any), `takes` (engine, reconvert, reread,
by-hand), `status` (open, fixed: waiting for the papers to be reconverted, done,
wont-fix) and a short `cost`. The records in the library's issues/ name their ticket in
`kind`, so the counts come from there, live; the README keeps a dated snapshot of them,
which the triage-conversions skill refreshes.
"""

import datetime
import sys
from collections import Counter

from paperlib import (
    LIBRARY_ROOT, TICKET_STATUSES, TICKET_TAKES, TICKETS_DIR, all_issues, is_open, load_tickets,
)

ORDER = {"open": 0, "fixed": 1, "wont-fix": 2, "done": 3}

HEADER = """# Conversion tickets

One file per cause of conversion problems: what is broken, how to fix it, what it gives and
what it takes. The papers each one touches are recorded in a library's `issues/`, one record
per problem, whose `kind` is the ticket's id (`paperlib issues --kind <id>` lists them).

- **Takes**: `engine` a change to the converters, with a fixture; `reconvert` the papers
  must be converted again to get it (`paperlib reconvert --issue <id>`, overnight for PDF
  papers); `reread` some notes rest on the broken part and are read again; `by-hand` an
  edit in the paper, marked `<!-- hand-edited -->`.
- **Status**: `open`; `fixed` in the engine, waiting for the reconversion (then
  `paperlib issues close <id> --state <file>`); `done`; `wont-fix`.

The `triage-conversions` skill files new problems under tickets and refreshes this table;
`fix-conversions <ids>` fixes tickets in the engine. Generated by `paperlib tickets --write`;
edit the tickets, not this file.
"""


def summary():
    tickets = load_tickets()
    papers, records, key = Counter(), Counter(), Counter()
    for stem, recs in all_issues().items():
        for kind in {r.get("kind") for r in recs if is_open(r)}:
            papers[kind] += 1
        for r in recs:
            if is_open(r):
                records[r.get("kind")] += 1
                key[r.get("kind")] += bool(r.get("key-content"))
    rows = []
    for tid, t in tickets.items():
        rows.append({"id": tid, "title": t.get("title", ""), "takes": t.get("takes") or [],
                     "status": t.get("status", "open"), "cost": t.get("cost", ""),
                     "papers": papers[tid], "records": records[tid], "key": key[tid]})
    rows.sort(key=lambda r: (ORDER.get(r["status"], 9), -r["key"], -r["papers"], r["id"]))
    orphans = {k: papers[k] for k in papers if k not in tickets}
    return rows, orphans


def problems(tickets):
    out = []
    for tid, t in tickets.items():
        if t["path"].stem != tid:
            out.append(f"{t['path'].name}: id `{tid}` differs from the file name")
        if not t.get("title"):
            out.append(f"{t['path'].name}: no title")
        if t.get("status", "open") not in TICKET_STATUSES:
            out.append(f"{t['path'].name}: status `{t.get('status')}` is not one of {sorted(TICKET_STATUSES)}")
        bad = set(t.get("takes") or []) - TICKET_TAKES
        if bad:
            out.append(f"{t['path'].name}: takes {sorted(bad)} not in {sorted(TICKET_TAKES)}")
    return out


def table(rows):
    lines = ["| Ticket | Takes | Status | Papers | Key content | Cost |", "|---|---|---|---|---|---|"]
    for r in rows:
        takes = " ".join(f"`{t}`" for t in r["takes"])
        lines.append(f"| [{r['title']}]({r['id']}.md) | {takes} | {r['status']} | {r['papers'] or ''} "
                     f"| {r['key'] or ''} | {r['cost']} |")
    return "\n".join(lines)


def main(argv):
    if any(a not in ("--write",) for a in argv):
        sys.exit(__doc__)
    rows, orphans = summary()
    for p in problems(load_tickets()):
        print(f"  ticket problem: {p}")
    print(f"tickets in {TICKETS_DIR}")
    print(f"{'ticket':34} {'status':9} {'papers':>6} {'key':>4}  takes")
    for r in rows:
        print(f"{r['id']:34} {r['status']:9} {r['papers']:6} {r['key']:4}  {' '.join(r['takes'])}")
    for kind, n in sorted(orphans.items(), key=lambda kv: -kv[1]):
        print(f"{str(kind):34} {'untriaged' if kind == 'new' else 'NO TICKET':9} {n:6}")
    if "--write" in argv:
        today = datetime.date.today().isoformat()
        text = (HEADER + f"\n## Tickets\n\nPapers and key-content counts from the library "
                f"`{LIBRARY_ROOT.name}` on {today}.\n\n" + table(rows) + "\n")
        (TICKETS_DIR / "README.md").write_text(text, encoding="utf-8")
        print(f"tickets: wrote {TICKETS_DIR.name}/README.md")


if __name__ == "__main__":
    main(sys.argv[1:])
